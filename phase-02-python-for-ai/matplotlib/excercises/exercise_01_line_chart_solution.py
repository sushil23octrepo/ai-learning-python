import matplotlib.pyplot as plt

# ============================================================
# MATPLOTLIB EXERCISE 01 — LINE CHART
# Reference solution.
# ============================================================

months = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
]

revenue = [
    120000,
    135000,
    128000,
    150000,
    165000,
    180000,
]


# ------------------------------------------------------------
# 1. Plot Month vs Revenue.
# 2. Use circle markers.
# ------------------------------------------------------------

# months are displayed on the X-axis.
# revenue values are displayed on the Y-axis.
# marker="o" shows every individual data point.
plt.plot(
    months,
    revenue,
    marker="o",
)


# ------------------------------------------------------------
# 3. Add the chart title.
# ------------------------------------------------------------

plt.title("Monthly Revenue")


# ------------------------------------------------------------
# 4. Add X-axis label.
# ------------------------------------------------------------

plt.xlabel("Month")


# ------------------------------------------------------------
# 5. Add Y-axis label.
# ------------------------------------------------------------

plt.ylabel("Revenue")


# ------------------------------------------------------------
# 6. Display grid lines.
# ------------------------------------------------------------

plt.grid(True)


# ------------------------------------------------------------
# 7. Display the chart.
# ------------------------------------------------------------

plt.show()
