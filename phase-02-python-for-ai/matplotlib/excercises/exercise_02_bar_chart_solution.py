import matplotlib.pyplot as plt

# ============================================================
# MATPLOTLIB EXERCISE 02 — BAR CHART
# Reference solution.
# ============================================================

products = [
    "Laptop",
    "Phone",
    "Tablet",
    "Monitor",
]

units_sold = [
    120,
    200,
    90,
    150,
]


# ------------------------------------------------------------
# 1. Plot Product vs Units Sold.
# ------------------------------------------------------------

# bar() creates one vertical bar for each product.
bars = plt.bar(
    products,
    units_sold,
)


# ------------------------------------------------------------
# 2. Add chart title.
# ------------------------------------------------------------

plt.title("Product Sales")


# ------------------------------------------------------------
# 3. Add X-axis label.
# ------------------------------------------------------------

plt.xlabel("Product")


# ------------------------------------------------------------
# 4. Add Y-axis label.
# ------------------------------------------------------------

plt.ylabel("Units Sold")


# ------------------------------------------------------------
# 5. Add horizontal grid lines.
# ------------------------------------------------------------

plt.grid(axis="y")


# ------------------------------------------------------------
# 6. Display the value on each bar.
# ------------------------------------------------------------

# bar_label() needs the BarContainer returned by plt.bar().
plt.bar_label(bars)


# ------------------------------------------------------------
# 7. Display the chart.
# ------------------------------------------------------------

plt.show()
