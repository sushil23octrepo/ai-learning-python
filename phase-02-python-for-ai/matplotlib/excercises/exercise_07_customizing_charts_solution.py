import matplotlib.pyplot as plt

# ============================================================
# MATPLOTLIB EXERCISE 07 — CUSTOMIZING CHARTS
# Reference solution.
# ============================================================

epochs = [
    1,
    2,
    3,
    4,
    5,
    6,
]

accuracy = [
    0.62,
    0.70,
    0.76,
    0.81,
    0.85,
    0.88,
]


# ------------------------------------------------------------
# 1. Set chart size.
# ------------------------------------------------------------

plt.figure(
    figsize=(8, 5),
)


# ------------------------------------------------------------
# 2. Create customized line chart.
# ------------------------------------------------------------

plt.plot(
    epochs,
    accuracy,
    # Circle markers.
    marker="o",
    # Dashed line.
    linestyle="--",
    # Line thickness.
    linewidth=2,
    # Marker size.
    markersize=8,
)


# ------------------------------------------------------------
# 3. Add chart title.
# ------------------------------------------------------------

plt.title("Model Accuracy by Epoch")


# ------------------------------------------------------------
# 4. Add axis labels.
# ------------------------------------------------------------

plt.xlabel("Epoch")

plt.ylabel("Accuracy")


# ------------------------------------------------------------
# 5. Set Y-axis range.
# ------------------------------------------------------------

# Accuracy values generally range between 0 and 1.
plt.ylim(
    0,
    1,
)


# ------------------------------------------------------------
# 6. Add annotation to best accuracy.
# ------------------------------------------------------------

plt.annotate(
    "Best Accuracy",
    # Actual data point.
    xy=(6, 0.88),
    # Position where annotation text appears.
    xytext=(4, 0.94),
    # Arrow pointing to the data point.
    arrowprops={
        "arrowstyle": "->",
    },
)


# ------------------------------------------------------------
# 7. Display grid.
# ------------------------------------------------------------

plt.grid(True)


# ------------------------------------------------------------
# 8. Adjust layout.
# ------------------------------------------------------------

plt.tight_layout()


# ------------------------------------------------------------
# 9. Display chart.
# ------------------------------------------------------------

plt.show()
