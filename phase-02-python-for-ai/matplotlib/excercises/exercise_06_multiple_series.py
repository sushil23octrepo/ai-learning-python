import matplotlib.pyplot as plt

# ============================================================
# MATPLOTLIB EXERCISE 06 — MULTIPLE SERIES
# Reference solution.
# ============================================================

months = [
    "Jan",
    "Feb",
    "Mar",
    "Apr",
    "May",
    "Jun",
]

planned_revenue = [
    120000,
    130000,
    140000,
    150000,
    160000,
    170000,
]

actual_revenue = [
    115000,
    135000,
    138000,
    155000,
    165000,
    180000,
]


# ------------------------------------------------------------
# 1. Control chart size.
# ------------------------------------------------------------

plt.figure(
    figsize=(8, 5),
)


# ------------------------------------------------------------
# 2. Plot planned revenue.
# ------------------------------------------------------------

plt.plot(
    months,
    planned_revenue,
    marker="o",
    label="Planned Revenue",
)


# ------------------------------------------------------------
# 3. Plot actual revenue.
# ------------------------------------------------------------

plt.plot(
    months,
    actual_revenue,
    marker="o",
    label="Actual Revenue",
)


# ------------------------------------------------------------
# 4. Add title and labels.
# ------------------------------------------------------------

plt.title("Planned vs Actual Revenue")

plt.xlabel("Month")

plt.ylabel("Revenue")


# ------------------------------------------------------------
# 5. Display legend.
# ------------------------------------------------------------

plt.legend()


# ------------------------------------------------------------
# 6. Display grid.
# ------------------------------------------------------------

plt.grid(True)


# ------------------------------------------------------------
# 7. Adjust layout.
# ------------------------------------------------------------

plt.tight_layout()


# ------------------------------------------------------------
# 8. Display chart.
# ------------------------------------------------------------

plt.show()
