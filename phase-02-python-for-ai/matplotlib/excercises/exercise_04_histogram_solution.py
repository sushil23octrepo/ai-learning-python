import matplotlib.pyplot as plt

# ============================================================
# MATPLOTLIB EXERCISE 04 — HISTOGRAM
# Reference solution.
# ============================================================

exam_scores = [
    45,
    52,
    55,
    60,
    62,
    65,
    68,
    70,
    72,
    75,
    78,
    80,
    82,
    85,
    88,
    90,
    92,
    95,
]


# ------------------------------------------------------------
# 1. Plot exam score distribution.
# ------------------------------------------------------------

# bins=6 divides the score range into 6 numeric groups.
plt.hist(
    exam_scores,
    bins=6,
)


# ------------------------------------------------------------
# 2. Add chart title.
# ------------------------------------------------------------

plt.title("Exam Score Distribution")


# ------------------------------------------------------------
# 3. Add X-axis label.
# ------------------------------------------------------------

plt.xlabel("Exam Score")


# ------------------------------------------------------------
# 4. Add Y-axis label.
# ------------------------------------------------------------

plt.ylabel("Student Count")


# ------------------------------------------------------------
# 5. Add horizontal grid lines.
# ------------------------------------------------------------

plt.grid(axis="y")


# ------------------------------------------------------------
# 6. Display chart.
# ------------------------------------------------------------

plt.show()
